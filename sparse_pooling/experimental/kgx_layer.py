DENSE_VARIANTS = ("kgen", "lowered", "direct", "idf_rmw", "idf")
REFERENCE_VARIANTS = ("kgen", "lowered")  # the existing kgen K = 64 kernels (kgx_lowering.KgenRoute)


def _mark(name):
    from ..kernels import cuda_ops

    cuda_ops._mark(name)


@torch.no_grad()
def records_from_feat(L: KLayout, feat: torch.Tensor, blk_buckets: torch.Tensor) -> torch.Tensor:
    """idx [G, NB, 64] of an S = K graph rebuilt from its sets (every valid record = feat[q]; padded blocks
    copy the output's first record, as ``kgen_graph.generate``)."""
    G, NB, K = L.groups, L.blocks_per_group, L.fan_in
    dev = feat.device
    b = blk_buckets.to(dev).to(torch.int64)
    rb = torch.repeat_interleave(torch.arange(len(b), device=dev), b[:, 3])
    kb = torch.arange(len(rb), device=dev) - torch.repeat_interleave(torch.cumsum(b[:, 3], 0) - b[:, 3], b[:, 3])
    idx = torch.empty((G * NB, K), dtype=torch.int16, device=dev)
    fb = b[rb, 1] * NB + b[rb, 2] + kb
    idx[fb] = feat[b[rb, 0]]
    idx = idx.view(G, NB, K)
    nvb = L.valid_blocks(dev)
    pad = torch.arange(NB, device=dev)[None, :] >= nvb[:, None]
    idx[pad] = idx[:, :1, :].expand(G, NB, K)[pad]
    return idx


class _Rt:
    def __init__(self, layer: "KgxLayer"):
        from ..backends.capabilities import query
        from ..backends.dispatch import kgx_dx_group_warps
        from .kgx_runtime import kgx_backend

        dev = layer.sg_feat.device
        self.backend = kgx_backend(dev)
        self.caps = query(dev)
        self.cfg = self.backend.cfg
        L = layer.layout
        self.sg = KX.KxExec(L.blocks_per_group, L.block, layer.counts, layer.sg_feat, layer.kg_buckets, layer.tile,
                            dw_per_cta=self.cfg["dw_warps"], group_keep=layer.group_keep(),
                            run_items=layer.run_items())
        self.dx_group_warps = kgx_dx_group_warps(self.caps, layer.kvariant, L.input_dim, layer.sg_feat.shape[1],
                                                 self.cfg)


class KgxFunction(torch.autograd.Function):
    @staticmethod
    def forward(ctx, x, w, b, layer: "KgxLayer"):
        if layer.kvariant in REFERENCE_VARIANTS:
            return _route_forward(ctx, x, w, b, layer)
        rt = layer._runtime()
        L = layer.layout
        B = x.shape[0]
        layer._check_call(B)
        xc = x.to(torch.bfloat16).contiguous()
        wc, bc = w.contiguous(), b.contiguous()
        _mark("fwd.begin")
        xt = xc.t().contiguous()
        _mark("fwd.layout")
        ysum = torch.zeros((L.groups, B), device=x.device, dtype=torch.float32)
        _mark("fwd.zero")
        a = layer._args(rt, xt, wc, bc, B)
        a.items, a.chunks, a.ysum = rt.sg.items.data_ptr(), rt.sg.chunks.data_ptr(), ysum.data_ptr()
        tok = layer._tokens("fwd", rt)
        n_tiles = math.ceil(B / tok)
        rt.backend.launch("fwd", layer.kvariant, a, 0, rt.sg.chunks.shape[0], n_tiles, x.device)
        _mark("fwd.kernel")
        if rt.sg.bias_only is not None:  # all-zero weight rows (dropped groups): z = bias, exactly
            slot, gg = rt.sg.bias_only
            const = torch.zeros(L.groups, device=x.device, dtype=torch.float32).index_add_(
                0, gg, torch.relu(bc.reshape(-1)[slot].float()))
            _mark("fwd.bias_only")
            pre = ((ysum + const[:, None]) / layer.counts_f[:, None]).t().contiguous()
        else:
            pre = (ysum / layer.counts_f[:, None]).t().contiguous()
        _mark("fwd.finalize")
        ctx.layer = layer
        ctx.route = False
        ctx.x_dtype = x.dtype
        ctx.save_for_backward(xc, w, b)
        layer.last_info.update(forward_backend="kgx", forward_kernel=f"kgx_{layer.kvariant}",
                               kgx_fwd=dict(ctas=rt.sg.chunks.shape[0] * n_tiles, token_tiles=n_tiles,
                                            chunks=rt.sg.chunks.shape[0], items=rt.sg.items.shape[0], tokens=tok,
                                            launches=1))
        return pre

    @staticmethod
    def backward(ctx, dy):
        layer: KgxLayer = ctx.layer
        if ctx.route:
            return _route_backward(ctx, dy, layer)
        xc, w, b = ctx.saved_tensors
        rt = layer._runtime()
        B, D = xc.shape
        _mark("bwd.begin")
        c1T = (dy.float() / layer.counts_f[None, :]).t().contiguous()  # Mean: dL/dpre / n_g, [G, B]
        _mark("bwd.coef")
        xt = xc.t().contiguous()
        _mark("bwd.layout")
        dxt = torch.zeros((D, B), device=xc.device, dtype=torch.float32)
        _mark("bwd.dx_init")
        mg_w, mg_b = getattr(w, "main_grad", None), getattr(b, "main_grad", None)
        use_main = mg_w is not None and mg_b is not None
        dw = mg_w if use_main else torch.zeros(w.shape, device=w.device, dtype=torch.float32)
        db = mg_b if use_main else torch.zeros(b.shape, device=b.device, dtype=torch.float32)
        a = layer._args(rt, xt, w.contiguous(), b.contiguous(), B)
        a.c1T, a.dXT, a.dW, a.dB = c1T.data_ptr(), dxt.data_ptr(), dw.data_ptr(), db.data_ptr()
        a.items, a.chunks, a.dx_group_warps = rt.sg.items.data_ptr(), rt.sg.chunks.data_ptr(), rt.dx_group_warps
        split = int(layer.plan.grad_precision == "split")
        tok = layer._tokens("dx", rt)
        n_tiles = math.ceil(B / tok)
        n_dx_chunks = rt.sg.chunks.shape[0]
        if layer.kvariant == "csr":  # static neuron windows (kgx_sparse.csr_windows)
            wins, wch = layer.dx_windows(rt)
            a.wins, a.chunks = wins.data_ptr(), wch.data_ptr()
            n_dx_chunks = wch.shape[0]
        rt.backend.launch("dx", layer.kvariant, a, split, n_dx_chunks, n_tiles, xc.device)
        _mark("bwd.dx")
        a.tasks, a.chunks = rt.sg.tasks.data_ptr(), rt.sg.dw_chunks.data_ptr()
        rt.backend.launch("dw", layer.kvariant, a, split, rt.sg.dw_chunks.shape[0], 0, xc.device)
        _mark("bwd.dw")
        if rt.sg.bias_only is not None:  # db of all-zero weight rows: sum_t c1 act'(bias)
            slot, gg = rt.sg.bias_only
            csum = c1T.sum(1)
            bo = b.detach().reshape(-1)[slot].float()
            db.view(-1).index_add_(0, slot, csum[gg] * (bo > 0).float())
            _mark("bwd.bias_only")
        layer.last_info.update(backward_backend="kgx", dx_kernel=f"kgx_{layer.kvariant}",
                               dw_kernel=f"kgx_{layer.kvariant}", grad_precision=layer.grad_scheme(),
                               grad_precision_requested=layer.plan.grad_precision,
                               kgx_dx=dict(ctas=n_dx_chunks * n_tiles, tokens=tok,
                                           group_warps=rt.dx_group_warps,
                                           reduction=layer._dx_reduction(rt), launches=1),
                               kgx_dw=dict(ctas=rt.sg.dw_chunks.shape[0], tasks=rt.sg.tasks.shape[0], launches=1))
        dx = dxt.t().to(ctx.x_dtype, memory_format=torch.contiguous_format)
        gw = None if use_main else dw.to(w.dtype)
        gb = None if use_main else db.to(b.dtype)
        return dx, gw, gb, None


def _route_forward(ctx, x, w, b, layer):
    """Reference variants: the kgen K = 64 kernels on the layer's tensors (physical C = 256 views if C > 256)."""
    r = layer._route()
    L = layer.layout
    B = x.shape[0]
    why = r.reason(layer, B)
    if why:
        raise ValueError(f"kgen reference route cannot run this call: {why}")
    layer._note_execution(B)
    xc = x.to(torch.bfloat16).contiguous()
    wc, bc = w.contiguous(), b.contiguous()
    _mark("fwd.begin")
    xt = xc.t().contiguous()
    _mark("fwd.layout")
    ysum = torch.zeros((L.groups, B), device=x.device, dtype=torch.float32)
    _mark("fwd.zero")
    a = r.args(layer, xt, wc, bc, B)
    a.items, a.chunks, a.ysum = r.sg.items.data_ptr(), r.sg.chunks.data_ptr(), ysum.data_ptr()
    n_tiles = math.ceil(B / r.tokens("fwd"))
    r.backend.launch(64, "fwd", a, layer.level.act_id, 0, r.sg.chunks.shape[0], n_tiles, x.device)
    _mark("fwd.kernel")
    pre = (ysum / layer.counts_f[:, None]).t().contiguous()
    _mark("fwd.finalize")
    ctx.layer = layer
    ctx.route = True
    ctx.x_dtype = x.dtype
    ctx.save_for_backward(xc, w, b)
    layer.last_info.update(forward_backend="kgen", forward_kernel=f"kgen_{layer.kvariant}",
                           kgx_fwd=dict(ctas=r.sg.chunks.shape[0] * n_tiles, token_tiles=n_tiles,
                                        chunks=r.sg.chunks.shape[0], items=r.sg.items.shape[0],
                                        tokens=r.tokens("fwd"), launches=1))
    return pre


def _route_backward(ctx, dy, layer):
    r = layer._route()
    xc, w, b = ctx.saved_tensors
    B, D = xc.shape
    _mark("bwd.begin")
    c1T = (dy.float() / layer.counts_f[None, :]).t().contiguous()
    _mark("bwd.coef")
    xt = xc.t().contiguous()
    _mark("bwd.layout")
    dxt = torch.zeros((D, B), device=xc.device, dtype=torch.float32)
    _mark("bwd.dx_init")
    mg_w, mg_b = getattr(w, "main_grad", None), getattr(b, "main_grad", None)
    use_main = mg_w is not None and mg_b is not None
    dw = mg_w if use_main else torch.zeros(w.shape, device=w.device, dtype=torch.float32)
    db = mg_b if use_main else torch.zeros(b.shape, device=b.device, dtype=torch.float32)
    a = r.args(layer, xt, w.contiguous(), b.contiguous(), B)
    a.c1T, a.dXT, a.dW, a.dB = c1T.data_ptr(), dxt.data_ptr(), dw.data_ptr(), db.data_ptr()
    a.items, a.chunks, a.dx_group_warps = r.sg.items.data_ptr(), r.sg.chunks.data_ptr(), r.dx_group_warps
    split = int(layer.plan.grad_precision == "split")
    n_tiles = math.ceil(B / r.tokens("dx"))
    r.backend.launch(64, "dx", a, layer.level.act_id, split, r.sg.chunks.shape[0], n_tiles, xc.device)
    _mark("bwd.dx")
    a.tasks, a.chunks = r.sg.tasks.data_ptr(), r.sg.dw_chunks.data_ptr()
    r.backend.launch(64, "dw", a, layer.level.act_id, split, r.sg.dw_chunks.shape[0], 0, xc.device)
    _mark("bwd.dw")
    layer.last_info.update(backward_backend="kgen", dx_kernel=f"kgen_{layer.kvariant}",
                           dw_kernel=f"kgen_{layer.kvariant}", grad_precision=layer.plan.grad_precision,
                           kgx_dx=dict(ctas=r.sg.chunks.shape[0] * n_tiles, tokens=r.tokens("dx"),
                                       group_warps=r.dx_group_warps,
                                       reduction="fp32_atomics" if r.dx_group_warps == 1 else "shared_cas+fp32_atomics",
                                       launches=1),
                           kgx_dw=dict(ctas=r.sg.dw_chunks.shape[0], tasks=r.sg.tasks.shape[0], launches=1))
    dx = dxt.t().to(ctx.x_dtype, memory_format=torch.contiguous_format)
    gw = None if use_main else dw.to(w.dtype)
    gb = None if use_main else db.to(b.dtype)
    return dx, gw, gb, None


class KgxLayer(nn.Module):
    """EXPERIMENTAL dense kgx layer (see the module docstring).  ``graph=(idx, feat, block buckets, GraphSpec)``
    reuses a given logical graph; otherwise ``kgen_graph.generate`` builds it from ``connectivity``.
    ``init``: "by_neuron" (valid-neuron draws independent of C; default) or "kgen" (kgen_layout.init_parameters,
    the canonical-order draws of the previous sweep)."""

    kvariant_family = DENSE_VARIANTS

    def __init__(self, input_dim: int, hidden_dim: int, output_dim: int, shared_neurons: int, connectivity,
                 variant: str = "direct", tile: int = 256, dtype=torch.bfloat16, device=None, seed: int = 0,
                 plan: Optional[PhysicalPlan] = None, graph=None, weights=None, init: str = "by_neuron",
                 keep_indices: Optional[bool] = None, _skip_params: bool = False):
        super().__init__()
        if dtype != torch.bfloat16:
            raise ValueError("kgx: BF16 parameters only")
        self.level = LevelSpec(type="mean")
        self.layout = L = KLayout(input_dim, hidden_dim, output_dim, 64, shared_neurons)
        if L.block % 16:
            raise ValueError(f"kgx: C % 16 == 0 required (got {L.block})")
        self.plan = plan or PhysicalPlan()
        self.connectivity = connectivity
        device = torch.device(device or "cuda")
        counts = L.counts_tensor(device)
        if graph is None:
            idx, feat, ubk, st = KG.generate(input_dim, counts, L.block, 64, L.blocks_per_group, 1, connectivity, device)
            bk = KG.unit_to_block_buckets(ubk, counts, L.block, 1)
            spec = KG.GraphSpec(64, L.block, connectivity.input_supergroup_dim, connectivity.partition_rounds,
                                connectivity.seed, 1, connectivity.generation)
            self.graph_stats = dict(st, generator=KG.GENERATOR, generator_version=KG.GENERATOR_VERSION, quantum=1)
        else:
            idx, feat, bk, spec = graph
            self.graph_stats = dict(source=spec.source, quantum=spec.quantum)
        self.spec = spec
        S = feat.shape[1]
        self.index_free_ok = S == 64
        if self.index_free_ok:
            self.graph_stats["index_free_check"] = KX.check_index_free(idx.to(device), feat.to(device), bk.to(device),
                                                                       counts, L.block)
        if keep_indices is None:
            keep_indices = not self.index_free_ok or variant not in ("idf_rmw", "idf")
        self.register_buffer("indices", idx.to(device).contiguous() if keep_indices else None)
        del idx
        self.register_buffer("sg_feat", feat.to(device).contiguous())
        self.register_buffer("kg_buckets", bk.to(device).contiguous())
        self.register_buffer("kg_spec", torch.frombuffer(bytearray(spec.to_json().encode()), dtype=torch.uint8).clone())
        self.counts = counts.contiguous()
        self.counts_f = counts.to(torch.float32)
        self.init_rule = init
        if not _skip_params:
            if weights is None:
                if init == "by_neuron":
                    w, b = init_parameters_by_neuron(L, device, dtype, seed=seed)
                elif init == "kgen":
                    w, b = init_parameters(L, device, dtype, seed=seed)
                else:
                    raise ValueError(f"init {init!r}")
            else:
                w, b = weights
            self.weight = nn.Parameter(w.to(device).contiguous())
            self.bias = nn.Parameter(b.to(device).contiguous())
        self.init_seed = seed
        self.tile = tile
        self._rt = None
        self._rt_key = None
        self.last_info = {}
        self.kvariant = None
        self.select_variant(variant, tile)

    # ---- variant selection (benchmarks: interleaved variants on one layer)
    def select_variant(self, variant: str, tile: Optional[int] = None):
        if variant not in self.kvariant_family:
            raise ValueError(f"{type(self).__name__}: variant {variant!r} not in {self.kvariant_family}")
        if variant in ("idf_rmw", "idf") and not self.index_free_ok:
            raise ValueError(f"variant {variant!r} needs S = K = 64 (S = {self.sg_feat.shape[1]})")
        if variant == "kgen" and self.layout.block > 256:
            raise ValueError("variant 'kgen' needs C <= 256 (use 'lowered')")
        if variant == "lowered" and self.layout.block <= 256:
            raise ValueError("variant 'lowered' is for C > 256 (use 'kgen')")
        self.kvariant = variant
        if tile is not None:
            self.tile = tile
        self.last_info["execution"] = None
        return self

    def bench_variants(self):
        out = ["kgen" if self.layout.block <= 256 else "lowered", "direct"]
        return out + (["idf_rmw", "idf"] if self.index_free_ok else [])

    def _route(self):
        from .kgx_lowering import KgenRoute

        if getattr(self, "_route_obj", None) is None:
            self._route_obj = KgenRoute(self)
            self.last_info["kgen_route"] = dict(self._route_obj.stats)
        return self._route_obj

    def _note_execution(self, B):
        ex = self.last_info.get("execution")
        if ex is None or ex.get("batch") != B or ex.get("variant") != self.kvariant:
            r = self._route()
            self.last_info["execution"] = dict(variant=self.kvariant, batch=B, status="experimental (kgen kernels)",
                                               backend=f"kgen K = 64 ({self.kvariant})", build=r.backend.build_info(),
                                               tiling=r.backend.cfg_dict(64), dx_group_warps=r.dx_group_warps,
                                               route=dict(r.stats), grad_precision=self.plan.grad_precision,
                                               numerics=self.numerics(), index_bytes=self.index_bytes())

    @property
    def sg_buckets(self):
        return self.kg_buckets

    def _runtime(self) -> _Rt:
        key = (self.sg_feat.device, self.kg_buckets.data_ptr(), self.tile, self.kvariant)
        if self._rt is None or self._rt_key != key:
            self._rt = _Rt(self)
            self._rt_key = key
            self.last_info["kgx_work_lists"] = dict(self._rt.sg.stats)
        return self._rt

    def _tokens(self, kind: str, rt) -> int:
        c = rt.cfg
        if self.kvariant == "csr":
            return 32 * (c["csr_tokens_per_lane"] if kind == "fwd" else c["csr_dx_warps"])
        if kind == "fwd":
            return 16 * (c["fwd_mt_direct"] if self.kvariant == "direct" else c["fwd_mt_index_free"])
        return 16 * c["dx_mt"]

    def _dx_reduction(self, rt) -> str:
        if self.kvariant in ("idf", "tile"):
            return "register accumulation over records, warp-private slab copies (ordered sum), FP32 global atomics"
        if self.kvariant == "csr":
            return "warp-owned token columns (plain read-modify-write), FP32 global atomics"
        return "fp32_atomics" if rt.dx_group_warps == 1 else "shared_cas+fp32_atomics"

    def _check_call(self, B: int):
        from ..backends.dispatch import kgx_reason

        mode, why, strict = resolve_reduction(self.plan)
        rt = self._rt
        L = self.layout
        r = kgx_reason(rt.caps, self.kvariant, 64, L.block, self.sg_feat.shape[1], L.input_dim, B, self.level, self.plan,
                       mode == "deterministic", rt.cfg, self.tile)
        if r:
            raise ValueError(f"experimental kgx layer cannot run this call: {r}")
        self.last_info["reduction"] = {"mode": "fast", "reason": why}
        ex = self.last_info.get("execution")
        if ex is None or ex.get("batch") != B or ex.get("grad_precision") != self.grad_scheme() \
                or ex.get("variant") != self.kvariant:
            self.last_info["execution"] = dict(self.explain(B), grad_precision=self.grad_scheme(),
                                               grad_precision_requested=self.plan.grad_precision)

    def _wptrs(self, w):
        """(W, tmeta, rowptr, kix) pointers of this representation."""
        return w.data_ptr(), 0, 0, 0

    def group_keep(self):
        """[G NB C / 16] bool of the 16-neuron groups the kernels run (None: all; sparse formats: groups with an
        active weight)."""
        return None

    def run_items(self) -> bool:
        return True

    def _args(self, rt, xt, w, b, B):
        from .kgx_runtime import KxArgs

        L = self.layout
        W, tm, rp, kx = self._wptrs(w)
        if self.kvariant == "direct" and self.indices is None:
            raise ValueError("variant 'direct' needs the record indices (layer built with keep_indices=False)")
        idx = self.indices.data_ptr() if self.kvariant == "direct" else 0
        return KxArgs(xt.data_ptr(), xt.stride(0), idx, W, b.data_ptr(), self.counts.data_ptr(), self.sg_feat.data_ptr(),
                      0, 0, 0, tm, rp, kx, 0, 0, 0, 0, 0, 0,
                      B, L.groups, L.input_dim, self.sg_feat.shape[1], L.blocks_per_group, L.block, 1, 0)

    def explain(self, B: int = 8192) -> dict:
        rt = self._runtime()
        L = self.layout
        from ..backends.cuda import variants as V

        smem = {k: V.kgx_smem(k, self.kvariant, L.input_dim, self.sg_feat.shape[1], rt.cfg, rt.dx_group_warps)
                for k in ("fwd", "dx", "dw")}
        return dict(backend=f"kgx {self.kvariant} (experimental)", status="experimental", variant=self.kvariant,
                    device=dict(name=rt.caps.name, arch=rt.caps.arch, sm_count=rt.caps.sm_count,
                                smem_per_block_optin=rt.caps.smem_per_block_optin),
                    build=rt.backend.build_info(), tiling=dict(rt.cfg), smem_bytes=smem,
                    tokens=dict(fwd=self._tokens("fwd", rt), dx=self._tokens("dx", rt)),
                    dx_group_warps=rt.dx_group_warps, dx_reduction=self._dx_reduction(rt),
                    logical_C=L.block, physical_tile=self.tile, profile="none (one compiled tiling; no tuning profile)",
                    numerics=self.numerics(), batch=B, work_lists=dict(rt.sg.stats),
                    index_bytes=self.index_bytes(), launches=dict(fwd=1, dx=1, dw=1))

    def index_bytes(self) -> dict:
        """Index / metadata bytes this variant needs (record indices only for direct execution)."""
        L = self.layout
        rec = L.groups * L.blocks_per_group * 64 * 2
        f = max(1, L.block // 256) if self.kvariant == "lowered" else 1
        return dict(record_indices_needed=rec * f if self.kvariant in ("direct", "kgen", "lowered") else 0,
                    index_duplication=f,
                    record_indices_resident=0 if self.indices is None else self.indices.numel() * 2,
                    feature_sets=self.sg_feat.numel() * 2, block_buckets=self.kg_buckets.numel() * 4)

    def grad_scheme(self) -> str:
        """The dZ operand scheme the backward kernels actually execute (recorded instead of the request)."""
        return self.plan.grad_precision

    def numerics(self) -> str:
        p = "dZ as BF16 hi + lo pair" if self.plan.grad_precision == "split" else "dZ as one BF16"
        return ("BF16 x / W / bias operands, FP32 accumulation over all K = 64 products before one ReLU; backward "
                f"recomputes z; {p} in dX / dW products (FP32 accumulate); FP32 atomics for cross-CTA sums")

    def enable_main_grad(self):
        for p in (self.weight, self.bias):
            if getattr(p, "main_grad", None) is None:
                p.main_grad = torch.zeros(p.shape, device=p.device, dtype=torch.float32)

    def zero_main_grad(self):
        for p in (self.weight, self.bias):
            if getattr(p, "main_grad", None) is not None:
                p.main_grad.zero_()

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        lead = x.shape[:-1]
        y = KgxFunction.apply(x.reshape(-1, x.shape[-1]), self.weight, self.bias, self)
        return y.reshape(*lead, y.shape[-1])

    def _load_from_state_dict(self, state_dict, prefix, *args, **kwargs):
        sp = state_dict.get(prefix + "kg_spec")
        if sp is not None:
            got = KG.GraphSpec.from_json(bytes(sp.cpu().tolist()).decode())
            if got != self.spec:
                raise ValueError(f"checkpoint graph spec {got} != layer spec {self.spec}")
        super()._load_from_state_dict(state_dict, prefix, *args, **kwargs)
        self._rt = None

    # ---- logical record table / parameters (benchmarks/kcsr_graph.py)
    def logical_indices(self):
        return self.indices if self.indices is not None else records_from_feat(self.layout, self.sg_feat,
                                                                                self.kg_buckets)

    def kcsr_table(self):
        L = self.layout
        return KG.record_table(L.input_dim, L.hidden_dim, self.counts, L.block, 64, self.logical_indices(),
                               self.sg_feat, self.kg_buckets)

    def kcsr_validate(self):
        L = self.layout
        return KG.validate(L.input_dim, self.counts, L.block, 64, self.logical_indices(), self.sg_feat,
                           self.kg_buckets, self.spec.R)

    def dense_params(self):
        """(weights [G, NB, C, 64], bias [G, NB, C]) in logical canonical order (dense values, inactive = 0)."""
        return self.weight.detach(), self.bias.detach()

    # ---- representation-independent identity (experimental/canonical.py)
    def canon_params(self):
        return {"weight": self.weight, "bias": self.bias}

    def canon_rows(self, src, g, n):
        from .canonical import dense_rows

        return dense_rows(self, src, g, n)

    def canon_mask_rows(self, g, n):
        from .canonical import dense_mask_rows

        return dense_mask_rows(self, g, n)

    def kcsr_describe(self):
        L = self.layout
        rt = self._runtime()
        return dict(backend=f"kgx_{self.kvariant}", status="experimental", logical_K=64, logical_C=L.block,
                    physical_C=min(L.block, self.tile), physical_tile=self.tile, physical_subblocks=1,
                    index_duplication=1, NB=L.blocks_per_group, spec=json.loads(self.spec.to_json()),
                    padding_fraction=L.padding_fraction(), param_bytes=self.param_bytes(), index_bytes=self.index_bytes(),
                    init=INIT_BY_NEURON if self.init_rule == "by_neuron" else "kgen_layout.init_parameters",
                    init_seed=self.init_seed, tiling=dict(rt.cfg), dx_group_warps=rt.dx_group_warps,
                    numerics=self.numerics(), build=rt.backend.build_info(), work_lists=dict(rt.sg.stats))

    def param_bytes(self) -> dict:
        L = self.layout
        return dict(weights=self.weight.numel() * 2, bias=self.bias.numel() * 2,
                    valid_weight_slots=L.hidden_dim * 64, valid_biases=L.hidden_dim,
                    physical_weight_slots=self.layout.groups * self.layout.slots_per_group * 64)

    def extra_repr(self):
        L = self.layout
        return (f"EXPERIMENTAL kgx {self.kvariant}: in={L.input_dim}, hidden={L.hidden_dim:,}, out={L.groups}, K=64, "
                f"C={L.block}, tile={self.tile}, S={self.spec.S}, R={self.spec.R}, Mean(ReLU)")


@torch.no_grad()
def from_kgen(kg, variant: str = "direct", tile: int = 256, plan: Optional[PhysicalPlan] = None) -> KgxLayer:
    """A KgxLayer with EXACTLY the graph, weights and bias of a K = 64 KgenLayer (matched backend control)."""
    L = kg.layout
    if L.fan_in != 64:
        raise ValueError("from_kgen needs a K = 64 KgenLayer")
    spec = kg.spec
    return KgxLayer(L.input_dim, L.hidden_dim, L.groups, L.block, kg.connectivity, variant=variant, tile=tile,
                    device=kg.indices.device, plan=plan or PhysicalPlan(grad_precision=kg.plan.grad_precision),
                    graph=(kg.indices, kg.sg_feat, kg.kg_buckets, spec),
                    weights=(kg.weight.detach().clone(), kg.bias.detach().clone()), init="kgen")
