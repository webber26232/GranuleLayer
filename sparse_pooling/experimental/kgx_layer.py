"""EXPERIMENTAL K = 64 input-supergroup layers of the large-C / index-free / L1-sparsity study.

    y[b, g] = mean_{valid neurons i of g} ReLU(z_i(b)),   z_i = bias_i + sum_{k < 64} w_ik x[b, idx_r(i)[k]]

(the kgen model at K = 64; C neurons of a logical block share its record).  Logical C % 16 == 0, up to
2048; the graph is generated by ``kgen_graph.generate`` (quantum 1) exactly as for ``KgenLayer``.

Execution variants (``variant``; kernels/cuda/experimental/kgx/kgx.cuh):

* ``direct``   records gathered through their 64 indices (any S in [64, 256]); large C split into
               physical neuron tiles (``tile`` = 64 / 128 / 256 neurons per work item);
* ``idf``      index-free, S = K = 64 only: every record of a supergroup is the set itself (checked on the
               actual graph), so no record indices / local lookups exist; the 64 staged rows are the A
               operand of every record of the CTA; dX accumulated in registers over records;
* ``idf_rmw``  index-free gather but kgen's per-record dX slab read-modify-write (attribution ablation);
* ``kgen``     reference: the existing kgen K = 64 kernels on the same tensors (C <= 256);
* ``lowered``  reference for C > 256: the kgen kernels on physical C = 256 subblocks (kgx_lowering).

Sparse layers (frozen mask; ``kgx_sparse``): ``KgxTileLayer`` (16 x 16 weight tiles, compact values, k16-tile
masks per 16-neuron group) and ``KgxCsrLayer`` (unstructured, per-neuron CSR, CUDA cores).  Every valid
neuron keeps its bias, activation and db; the pooling denominator stays n_g.

BF16 parameters / inputs, FP32 accumulation, split (hi + lo) or BF16 dZ operands, FP32 main_grad,
fast FP32-atomic reductions only.  Never selected by SparsePoolingLayer.
"""
