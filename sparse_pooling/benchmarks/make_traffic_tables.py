"""Render results/traffic/*.json into results/traffic/TABLES.md (measured numbers only).

    python sparse_pooling/benchmarks/make_traffic_tables.py
"""
from __future__ import annotations

import json
import statistics
from pathlib import Path

R = Path(__file__).resolve().parent.parent / "results" / "traffic"
PH = ["fwd_kernel", "fwd_total", "dx_kernel", "dw_kernel", "bwd_total", "optimizer", "step"]


def load(pattern):
    out = []
    for p in sorted(R.glob(pattern)):
        d = json.loads(p.read_text())
        if "record" in d:
            out.append(dict(d["record"], _file=p.name, _ts=d.get("timestamp")))
    return out


def ms(rec, ph):
    v = rec["phases"].get(ph)
    return v["median_ms"] if v else None


def spread(rec, ph):
    v = rec["phases"].get(ph)
    return v["rep_median_spread_ms"] if v else None


def f(x, nd=1):
    return "-" if x is None else f"{x:,.{nd}f}"


def key(r):
    return (r["pooling"], r["hidden"], r["C"], r["grad_precision"])


def matrix_table(orig, opt):
    o = {key(r): r for r in orig}
    lines = ["| Pooling | H | C | Grad | Variant | dW staging / cfg | dX warps | Fwd kernel | Fwd total | dX kernel "
             "| dW kernel | Bwd total | Optimizer | Step | Peak alloc | Peak reserved |",
             "|---|---:|---:|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in sorted(opt, key=lambda r: (r["pooling"] != "mean", r["pooling"], r["hidden"], r["C"], r["grad_precision"])):
        for name, rr in (("original", o.get(key(r))), ("optimized", r)):
            if rr is None:
                continue
            nd = 2 if rr["hidden"] <= 1_000_000 else 1
            lines.append(
                f"| {rr['pooling']} | {rr['hidden']:,} | {rr['C']} | {rr['grad_precision']} | {name} "
                f"| {rr.get('dw_staging_used')} / {rr.get('dw_cfg')} | {rr.get('dx_warps') or '-'} "
                + " | ".join(f(ms(rr, p), nd) for p in PH)
                + f" | {rr['peak_allocated_bytes'] / 2**30:.2f} GiB | {rr['peak_reserved_bytes'] / 2**30:.2f} GiB |")
        oo = o.get(key(r))
        if oo is not None and ms(oo, "step"):
            sp = lambda p: (ms(oo, p) / ms(r, p)) if ms(oo, p) and ms(r, p) else None  # noqa: E731
            lines.append(f"| | | | | speedup | | | {f(sp('fwd_kernel'), 3)} | {f(sp('fwd_total'), 3)} "
                         f"| {f(sp('dx_kernel'), 3)} | {f(sp('dw_kernel'), 3)} | {f(sp('bwd_total'), 3)} | "
                         f"{f(sp('optimizer'), 3)} | {f(sp('step'), 3)} | | |")
    return "\n".join(lines)


def ab_table(recs):
    groups = {"original": [], "optimized": []}
    for r in recs:
        groups["original" if r.get("dw_staging_used") == "full" else "optimized"].append(r)
    lines = ["| Variant | rounds | " + " | ".join(PH) + " |", "|---|---:|" + "---:|" * len(PH)]
    med = {}
    for name, rs in groups.items():
        if not rs:
            continue
        med[name] = {p: statistics.median(ms(r, p) for r in rs) for p in PH}
        rng = {p: (min(ms(r, p) for r in rs), max(ms(r, p) for r in rs)) for p in PH}
        lines.append(f"| {name} | {len(rs)} | " + " | ".join(
            f"{med[name][p]:.1f} ({rng[p][0]:.1f}-{rng[p][1]:.1f})" for p in PH) + " |")
    if len(med) == 2:
        lines.append("| speedup (median) | | " + " | ".join(
            f"{med['original'][p] / med['optimized'][p]:.3f}x" for p in PH) + " |")
    return "\n".join(lines), med


def ablation_table(recs):
    lines = ["| Ablation (wrong results) | H | dW staging / cfg | Fwd kernel | dX kernel | dW kernel | Step |",
             "|---|---:|---|---:|---:|---:|---:|"]
    for r in sorted(recs, key=lambda r: (-r["hidden"], r["tag"] != "ref", r["tag"], r.get("dw_staging_used"),
                                         r.get("dw_cfg"))):
        lines.append(f"| {r['tag']} {r.get('nvcc_extra') or ''} | {r['hidden']:,} | {r.get('dw_staging_used')} / "
                     f"{r.get('dw_cfg')} | {f(ms(r, 'fwd_kernel'))} | {f(ms(r, 'dx_kernel'))} | "
                     f"{f(ms(r, 'dw_kernel'))} | {f(ms(r, 'step'))} |")
    return "\n".join(lines)


def main():
    parts = ["# Per-kernel measurements (generated by benchmarks/make_traffic_tables.py)\n",
             "Medians over all steps of all repetitions (CUDA events at phase boundaries); "
             "ranges in the A/B table are min-max of the per-round medians.\n"]
    ab = load("kernels_*_ab_r*.json")
    if ab:
        t, _ = ab_table(ab)
        parts += ["\n## Interleaved A/B, H = 100M, C = 64, Mean(ReLU), split\n", t]
    orig, opt = load("kernels_*_original.json"), load("kernels_*_optimized.json")
    if opt:
        parts += ["\n## Configuration matrix: original vs optimized\n", matrix_table(orig, opt)]
    abl = [r for r in load("kernels_*.json") if r.get("tag") and r["tag"] not in ("original", "optimized")
           and not r["tag"].startswith("ab_r")]
    if abl:
        parts += ["\n## Attribution ablations (timing only)\n", ablation_table(abl)]
    (R / "TABLES.md").write_text("\n".join(parts) + "\n")
    print("wrote", R / "TABLES.md")


if __name__ == "__main__":
    main()
